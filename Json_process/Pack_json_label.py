import json
import os

import pandas as pd

if __name__ == '__main__':
    root = 'dataset'
    User_label_dict = {}
    user_list = [name for name in os.listdir(root) if os.path.isdir(os.path.join(root, name))]
    for User_num in user_list:
        # User_id = 18
        User_id = User_num.replace('user_', '')
        print('Now user: ' + str(User_id))
        path = os.path.join(root, ('user_' + str(User_id)))
        Label_file = os.path.join(path, 'questionnaire.csv')

        df = pd.read_csv(Label_file)
        Label = df.columns[1:20].tolist()
        for index, value in enumerate(Label):
            if '9+1' in value:
                Label[index] = value.replace('9+1', '33')

        data = df.iloc[0, 1:20].tolist()

        User_label_dict[User_id] = dict(zip(Label, data))
    with open('../Json_files/Label.json', 'w') as f:
        json.dump(User_label_dict, f)
